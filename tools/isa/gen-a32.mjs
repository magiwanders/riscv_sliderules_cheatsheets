// Generates src/isa/generated/a32.mjs, the instruction data of the A32 sheets (ARMv7-A, the ARM instruction set: integer,
// load / store, branch, coprocessor and system instructions), from LLVM's ARM TableGen description (spec/llvm/ARM.json)
// and src/isa/overlay/a32.json (sections, groups, mnemonics, assembly, descriptions, pseudocode). There is no Sail model
// of A32 written as encodings: spec/unofficial/a32/a32.sail, written by hand from the Arm ARM, must give every LLVM
// instruction the same bits, up to the fields' names (tools/isa/llvm-sail.mjs). A row may name its Sail clause (LDRH_i,
// LDRH_r: one LLVM record, two forms); LLVM records the sheet leaves out are listed, with the reason, in excludeLLVM.
//
//   npm run isa          (with --check only compares with the file on disk)
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readSail, sailInstructions } from './sail.mjs';
import { ROOT, fail, moduleText, writeOrCheck } from './common.mjs';
import { compare, encoding } from './llvm-sail.mjs';

const IMMEDIATES = ['imm', 'label', 'cimm'];
// LLVM's predicates: the architecture or extension an instruction comes from, as the sheets' Arch column says it
const LEVELS = [['HasVirtualization', 'Virtualization'], ['HasDivideInARM', 'Virtualization'], ['HasTrustZone', 'Security'], ['HasMP', 'MP'], ['HasV7', 'ARMv7'],
  ['HasDB', 'ARMv7'], ['HasV6T2', 'ARMv6T2'], ['HasV6K', 'ARMv6K'], ['HasV7Clrex', 'ARMv6K'], ['HasV6', 'ARMv6'], ['HasV5TE', 'ARMv5TE'], ['HasV5T', 'ARMv5T'], ['HasV4T', 'ARMv4T']];
const level = (def) => (LEVELS.find(([p]) => def.predicates.includes(p)) || [null, 'ARMv4'])[1];

export function generate() {
  const overlay = JSON.parse(readFileSync(join(ROOT, 'src', 'isa', 'overlay', 'a32.json'), 'utf8'));
  const llvm = JSON.parse(readFileSync(join(ROOT, 'spec', 'llvm', 'ARM.json'), 'utf8'));
  const sail = readSail({ files: [join(ROOT, 'spec', 'unofficial', 'a32', 'a32.sail')] });
  const byKey = new Map(sailInstructions({ sail, config: { xlen: 0, extensions: new Set(), immediates: IMMEDIATES } }).map((s) => [s.key, s]));
  const clauses = new Set(overlay.instructions.map((row) => row.sail || row.def));
  for (const k of byKey.keys()) if (!clauses.has(k)) fail(`${k}: in the Sail, on no row`);
  const placed = new Set();
  const instructions = overlay.instructions.map((row) => {
    const def = llvm.instructions[row.def] || fail(`overlay row ${row.def}: no LLVM instruction`);
    const s = byKey.get(row.sail || row.def) || fail(`${row.sail || row.def}: not in the Sail`);
    compare({ name: row.sail || row.def, s, def, llvmFixed: row.llvmFixed });
    placed.add(row.def);
    // nopc: registers that cannot be pc there (UNPREDICTABLE), written as rd!=15 in the encoding
    const enc = encoding({ s, fix: row.fix }).split(' ').map((t) => ((row.nopc || []).includes(t) ? `${t}!=15` : t)).join(' ');
    return { group: row.group, extension: row.extension ?? level(def), name: row.name, enc, asm: row.asm, description: row.description, pseudocode: row.pseudocode,
      ...(row.distinct ? { distinct: row.distinct } : {}), ...(row.immMax !== undefined ? { immMax: row.immMax } : {}) };
  });
  for (const name of Object.keys(overlay.excludeLLVM)) if (!llvm.instructions[name]) fail(`excludeLLVM ${name}: no such LLVM instruction`);
  const missing = Object.keys(llvm.instructions).filter((n) => !placed.has(n) && !overlay.excludeLLVM[n]);
  if (missing.length) fail(`A32: LLVM instructions no overlay row places: ${missing.join(', ')}`);
  const extensions = overlay.extensions.filter((e) => instructions.some((i) => i.extension === e));
  return { formats: overlay.formats, sections: overlay.sections, extensions, groups: overlay.groups, instructions, registers: overlay.registers || [] };
}

export function a32Module({ data = generate() } = {}) {
  return moduleText({
    header: [`Generated by tools/isa/gen-a32.mjs from LLVM's ARM TableGen (spec/llvm/ARM.json), the unofficial Sail`,
      `(spec/unofficial/a32/a32.sail) and src/isa/overlay/a32.json. Do not edit: change those and run npm run isa.`],
    exports: data,
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeOrCheck({ out: join(ROOT, 'src', 'isa', 'generated', 'a32.mjs'), text: a32Module() });
