// Generates src/isa/generated/a64.mjs, the instruction data of the A64 sheets (ARMv8.0-A: integer, loads and stores,
// branches and system, scalar floating point), from LLVM's AArch64 TableGen description (spec/llvm/AArch64.json) and
// src/isa/overlay/a64.json (sections, groups, mnemonics, assembly, descriptions, pseudocode). There is no Sail model of
// A64 written as encodings: spec/unofficial/a64/a64.sail, written by hand from the Arm ARM, must give every LLVM
// instruction the same bits, up to the fields' names (tools/isa/llvm-sail.mjs).
//
// LLVM prints A64 operands through its own printers (shifted immediates, bitmask immediates, extends), so the sheet's
// assembly is the overlay's, in the Sail's field names; the assemblers check it (npm run vectors:a64).
//
//   npm run isa          (with --check only compares with the file on disk)
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readSail, sailInstructions } from './sail.mjs';
import { ROOT, fail, moduleText, writeOrCheck } from './common.mjs';
import { compare, encoding } from './llvm-sail.mjs';

const IMMEDIATES = ['imm', 'simm', 'uoff', 'label', 'page'];

export function generate() {
  const overlay = JSON.parse(readFileSync(join(ROOT, 'src', 'isa', 'overlay', 'a64.json'), 'utf8'));
  const llvm = JSON.parse(readFileSync(join(ROOT, 'spec', 'llvm', 'AArch64.json'), 'utf8'));
  const sail = readSail({ files: [join(ROOT, 'spec', 'unofficial', 'a64', 'a64.sail')] });
  const byKey = new Map(sailInstructions({ sail, config: { xlen: 0, extensions: new Set(), immediates: IMMEDIATES } }).map((s) => [s.key, s]));
  for (const k of byKey.keys()) if (!llvm.instructions[k]) fail(`${k}: in the Sail, not in LLVM`);
  const placed = new Set();
  const instructions = overlay.instructions.map((row) => {
    const def = llvm.instructions[row.def] || fail(`overlay row ${row.def}: no LLVM instruction`);
    const s = byKey.get(row.def) || fail(`${row.def}: not in the Sail`);
    compare({ name: row.def, s, def, llvmFixed: row.llvmFixed });
    placed.add(row.def);
    return { group: row.group, extension: def.predicates.includes('HasFPARMv8') ? 'FP' : 'Base', name: row.name, enc: encoding({ s, fix: row.fix }),
      asm: row.asm, description: row.description, pseudocode: row.pseudocode, ...(row.immMax !== undefined ? { immMax: row.immMax } : {}) };
  });
  const missing = Object.keys(llvm.instructions).filter((n) => !placed.has(n));
  if (missing.length) fail(`A64: LLVM instructions no overlay row places: ${missing.join(', ')}`);
  return { formats: overlay.formats, sections: overlay.sections, extensions: overlay.extensions, groups: overlay.groups, instructions, registers: overlay.registers || [] };
}

export function a64Module({ data = generate() } = {}) {
  return moduleText({
    header: [`Generated by tools/isa/gen-a64.mjs from LLVM's AArch64 TableGen (spec/llvm/AArch64.json), the unofficial Sail`,
      `(spec/unofficial/a64/a64.sail) and src/isa/overlay/a64.json. Do not edit: change those and run npm run isa.`],
    exports: data,
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeOrCheck({ out: join(ROOT, 'src', 'isa', 'generated', 'a64.mjs'), text: a64Module() });
